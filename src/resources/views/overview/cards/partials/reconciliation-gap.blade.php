{{-- The reconciliation card's explanation: what each line means, an example (fictitious) and what the gap is
     made of. --}}
<p class="text-muted mb-1" style="font-size: 0.85rem;">
    <strong>How the totals above connect:</strong>
</p>
<ul class="text-muted mb-1" style="font-size: 0.8rem; padding-left: 1.2rem;">
    <li>
        <strong>Total growth</strong> = Investment total + Funding total (negative: the money you put in). It is
        everything you have beyond what you put in.
    </li>
    <li>
        <strong>Explained by gains</strong> = what you made selling (stock gains + dividends, from Gains Per Year) +
        what the shares you still hold gained or lost (the Investment Gain column). The percentage says how much of
        the growth these gains account for.
    </li>
    <li><strong>Gap</strong> = Total growth minus Explained by gains: growth no gain column captures.</li>
</ul>
<p class="text-muted mb-1" style="font-size: 0.8rem;">
    <strong>Example:</strong> you put in 10,000 &euro; and have 12,500 &euro; today: growth +2,500 &euro;. You sold
    for +1,500 &euro;, got 300 &euro; in dividends and the shares you still hold are up 600 &euro;: explained
    +2,400 &euro; (96 % of the growth), gap +100 &euro;.
</p>
<p class="text-muted mb-1" style="font-size: 0.8rem;">
    <strong>The gap usually comes from:</strong>
</p>
<ul class="text-muted mb-1" style="font-size: 0.8rem; padding-left: 1.2rem;">
    <li>
        Currency moves: Gains Per Year converts each year at its year-end rate, Funding and Investment convert at
        today&#039;s rate
    </li>
    <li>Interest on cash and savings accounts not recorded as dividends</li>
    <li>Transferred positions, whose virtual funding doesn&#039;t match real money put in</li>
    <li>Money held for others in your funding sources</li>
    <li>Fees outside trades (e.g. transfer fees): they lower Funding but are no trade loss</li>
</ul>
<p class="text-muted mb-0" style="font-size: 0.8rem;">
    A small, stable gap is normal. If it jumps, something is usually recorded wrong (a missing trade, cash balance or
    ledger entry). Never add Gains Per Year to Investment: Investment already holds every realized gain.
</p>
